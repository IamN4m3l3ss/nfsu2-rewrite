ALIASES = {"enter": "return", "esc": "escape", "ctrl": "lcontrol", "shift": "lshift", "alt": "lmenu", "pgup": "prior", "pgdn": "next"}


def code(name: str | int) -> int:
    if isinstance(name, int):
        return name
    n = name.lower()
    n = ALIASES.get(n, n)
    if n in DIK:
        return DIK[n]
    if n.startswith("0x"):
        return int(n, 16)
    raise KeyError(f"unknown key {name!r}")
