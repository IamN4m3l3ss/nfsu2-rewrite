#!/usr/bin/env python3
"""Generate rewrites for trivial accessors: functions whose whole body is one exact pattern (field / global getter,
constant, sign/zero-extending getter, setter). Writes game/systems/<system>/accessors_gen.cpp (macros from
game/framework/accessors.h) with a generic diff test per file.

  gen_accessors.py [--exclude FILE]     FILE: addresses to leave out (e.g. tools/re/modcheck.py exclude output)
Skips: already verified, registered by nfsu2-gcpc, field offsets >= 0x1000, and anything not matching exactly.
"""
import collections
import csv
import re
import sqlite3
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import kb  # noqa: E402
import xrefs  # noqa: E402

H = r"(0x[0-9a-f]+|\d+)"
RET = rf"ret(?: {H})?$"
PATTERNS = [
    ("ACC_GET32", rf"^mov eax, dword ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_GET32", rf"^mov eax, dword ptr \[ecx\] ; {RET}"),
    ("ACC_LEA", rf"^lea eax, \[ecx \+ {H}\] ; {RET}"),
    ("ACC_FLD", rf"^fld dword ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_CONST", rf"^mov eax, {H} ; {RET}"),
    ("ACC_CONST", rf"^xor eax, eax ; {RET}"),
    ("ACC_FLDG", rf"^fld dword ptr \[{H}\] ; {RET}"),
    ("ACC_GETG", rf"^mov eax, dword ptr \[{H}\] ; {RET}"),
    ("ACC_SX8", rf"^movsx eax, byte ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_ZX8", rf"^movzx eax, byte ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_SX16", rf"^movsx eax, word ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_ZX16", rf"^movzx eax, word ptr \[ecx \+ {H}\] ; {RET}"),
    ("ACC_SET32", r"^mov eax, dword ptr \[esp \+ 4\] ; mov dword ptr \[ecx \+ " + H + r"\], eax ; ret 4$"),
]
SYSTEM = [("zPhysics", "physics"), ("zAI", "ai"), ("zWorld", "world"), ("zTrack", "world"), ("zEAXSound", "audio"),
          ("zCamera", "camera"), ("zFe", "frontend"), ("zBWare", "bware"), ("zMisc", "misc"), ("filesys", "file")]


def num(s):
    return int(s, 0) if s else 0


def main(argv):
    exclude = set()
    if argv[:1] == ["--exclude"]:
        exclude = {int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", Path(argv[1]).read_text())}
    pe = xrefs.pe()
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    idx = sorted(kb.dump_index("pc"))
    names = kb.dump_index("pc")
    ver = {int(r["addr"], 16) for r in csv.DictReader((ROOT / "docs/symbols.csv").open()) if r["status"] == "verified"}
    gcpc = {int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]+),", (ROOT / "third_party/nfsu2-gcpc/replacements.cpp").read_text())}
    db = sqlite3.connect(f"file:{kb.DB}?mode=ro", uri=True) if kb.DB else None
    src = {}
    if db:
        for pa, sf in db.execute("select m.pc_addr, g.src_file from matches m join gc_functions g on g.addr = m.gc_addr"):
            src[pa] = sf or ""
    per = collections.defaultdict(list)
    for i, a in enumerate(idx[:-1]):
        if a >= 0x75BBFA or a in ver or a in gcpc or a in exclude:
            continue
        if idx[i + 1] - a > 32:
            continue
        ins = []
        for x in md.disasm(pe.get_data(a - 0x400000, 32), a):
            ins.append(f"{x.mnemonic} {x.op_str}".strip())
            if x.mnemonic == "ret":
                break
        text = " ; ".join(ins)
        for macro, pat in PATTERNS:
            m = re.match(pat, text)
            if not m:
                continue
            g = m.groups()
            if macro == "ACC_SET32":
                val, nargs = num(g[0]), 1
            elif len(g) == 1:  # no value in the pattern: [ecx] / xor eax, eax
                val, nargs = 0, num(g[0]) // 4
            else:
                val, nargs = num(g[0]), num(g[1]) // 4
            if macro in ("ACC_GET32", "ACC_LEA", "ACC_FLD", "ACC_SX8", "ACC_ZX8", "ACC_SX16", "ACC_ZX16", "ACC_SET32") and val >= 0xFF0:
                break
            if nargs > 8:  # the entry stubs copy at most 8 stack arguments
                break
            sysname = next((f for k, f in SYSTEM if k in src.get(a, "")), "misc")
            nm = re.sub(r"\W", "_", names.get(a, ("", "fn"))[1].split("(")[0])[:40].strip("_") or "fn"
            per[sysname].append((a, macro, f"{nm}_{a:06X}", val, nargs, text))
            break
    total = 0
    for sysname, items in per.items():
        out = ROOT / "game/systems" / sysname / "accessors_gen.cpp"
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = [f"// Generated by tools/re/gen_accessors.py: {len(items)} trivial accessors ({sysname}), each matching one exact",
                 "// instruction pattern of the original (shown per line). Diff test: game::acc::run_test.",
                 '#include "accessors.h"', ""]
        for a, macro, nm, val, nargs, text in items:
            lines.append(f"// {a:06X}: {text}")
            if macro == "ACC_SET32":
                lines.append(f"ACC_SET32(0x{a:08X}, {nm}, 0x{val:X});")
            else:
                lines.append(f"{macro}(0x{a:08X}, {nm}, 0x{val:X}u, {nargs});")
        anchor = items[0][2]
        lines += ["", f"NFSU2_DIFF_TEST(accessors_{sysname}) {{ return ::game::acc::run_test(ctx, \"accessors_{sysname}\", o_{anchor}); }}", ""]
        out.write_text("\n".join(lines))
        total += len(items)
        print(f"  {sysname:10} {len(items):4}  -> {out.relative_to(ROOT)}")
    print(f"{total} accessors generated")


if __name__ == "__main__":
    main(sys.argv[1:])
