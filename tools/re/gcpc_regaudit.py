#!/usr/bin/env python3
"""Register audit of every nfsu2-gcpc rewrite we register (gcpc_allow.inc + gcpc_hooked.inc).

Callers that keep using ECX/EDX after the call (directly, or implicitly as the next thiscall's `this`) need our
register-preserving thunk; nfsu2-gcpc's own audit missed some (0x503550 -> crash in Customize, 2026-11-15).
Writes game/systems/frontend/gcpc_preserve.inc ({addr, argBytes, calleePops} for gcpc_hooks.cpp) and prints the
functions that need a decision by hand:
  - the original itself writes ECX/EDX (restoring the entry value would then be wrong) -> excluded instead
  - cdecl with an unknown argument size (no `add esp, N` after the calls)              -> excluded instead
Exclusions go to gcpc_regexclude.inc. Run after changing either list.
"""
import re
import struct
import sys
from pathlib import Path

import capstone
from capstone import x86

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kb  # noqa: E402
import regcontract  # noqa: E402
import xrefs  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
FE = ROOT / "game/systems/frontend"
WRITES = {x86.X86_REG_ECX: "ecx", x86.X86_REG_CX: "ecx", x86.X86_REG_CL: "ecx", x86.X86_REG_CH: "ecx",
          x86.X86_REG_EDX: "edx", x86.X86_REG_DX: "edx", x86.X86_REG_DL: "edx", x86.X86_REG_DH: "edx"}


def load(p):
    return {int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", "".join(l for l in p.open() if not l.startswith("//")))}


def already_preserved():
    src = (ROOT / "third_party/nfsu2-gcpc/replacements.cpp").read_text()
    return {int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]+),[^\n]*\},\s*1,\s*\d+,\s*\d+\}", src)}


def body(a, nxt):
    base, data = xrefs.text()
    end = min(nxt.get(a, a + 256), a + 16384)
    return data[a - base:end - base]


def analyse(a, nxt):
    """(set of ecx/edx the original writes itself, ret N or None for plain ret)."""
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    writes, ret_n = set(), None
    furthest = a  # furthest branch target inside the function seen so far
    for ins in md.disasm(body(a, nxt), a):
        if ins.mnemonic.startswith("j") and ins.operands and ins.operands[0].type == x86.X86_OP_IMM:
            t = ins.operands[0].imm
            if a <= t < nxt.get(a, a + 16384):
                furthest = max(furthest, t)
        if ins.mnemonic in ("ret", "jmp") and ins.address >= furthest:
            if ins.mnemonic == "ret" and ins.op_str:
                ret_n = int(ins.op_str, 0)
            break  # end of the function
        if ins.mnemonic == "call":
            writes |= {"ecx", "edx"}  # a callee may change them; the original then leaves whatever it left
            continue
        _, w = ins.regs_access()
        writes |= {WRITES[r] for r in w if r in WRITES}
        if ins.mnemonic == "ret" and ins.op_str:
            ret_n = int(ins.op_str, 0)
    return writes, ret_n


def caller_cleanup(a):
    base, data = xrefs.text()
    sizes = set()
    for s in regcontract.call_sites(a):
        o = s + 5 - base
        if data[o:o + 2] == b"\x83\xC4":
            sizes.add(data[o + 2])
        elif data[o:o + 2] == b"\x81\xC4":
            sizes.add(struct.unpack_from("<I", data, o + 2)[0])
        else:
            sizes.add(None)
    return sizes


def main():
    regs = load(FE / "gcpc_allow.inc") | load(FE / "gcpc_hooked.inc")
    done = already_preserved()
    idx = sorted(kb.dump_index("pc"))
    nxt = {x: idx[i + 1] for i, x in enumerate(idx[:-1])}
    names = kb.dump_index("pc")
    preserve, exclude = [], []
    for a in sorted(regs - done):
        used = set()
        for s in regcontract.call_sites(a):
            used |= regcontract.reads_after(s)
        if not used & {"ecx", "edx"}:
            continue
        writes, ret_n = analyse(a, nxt)
        name = names.get(a, ("", "?"))[1]
        clash = writes & used & {"ecx", "edx"}
        if clash:
            exclude.append((a, f"callers read {sorted(clash)}, which the original itself changes"))
            continue
        if ret_n is not None:
            preserve.append((a, ret_n, 1, name))
            continue
        sizes = caller_cleanup(a)
        if None in sizes and len(sizes) > 1 or len(sizes) > 1:
            exclude.append((a, f"cdecl, argument size unclear {sorted(map(str, sizes))}"))
        elif sizes == {None} and "ecx" not in regcontract.entry_reads(a):
            exclude.append((a, "plain ret, no caller cleanup and not a thiscall: argument size unknown"))
        else:
            n = next(iter(sizes)) if sizes else 0
            preserve.append((a, n or 0, 0, name))
    with (FE / "gcpc_preserve.inc").open("w") as f:
        f.write("// Generated by tools/re/gcpc_regaudit.py: callers read ECX/EDX after these calls (also implicitly as the\n"
                "// next thiscall's this); the original never writes them. {addr, argBytes, calleePops}\n")
        for a, n, pops, name in preserve:
            f.write(f"    {{0x{a:06X}, {n}, {pops}}},  // {name}\n")
    with (FE / "gcpc_regexclude.inc").open("w") as f:
        f.write("// Generated by tools/re/gcpc_regaudit.py: register contract needs a decision by hand -> not registered.\n")
        for a, why in exclude:
            f.write(f"    0x{a:06X},  // {names.get(a, ('', '?'))[1]}: {why}\n")
    print(f"{len(regs)} registered, {len(done & regs)} already preserved by nfsu2-gcpc; "
          f"+{len(preserve)} preserve, {len(exclude)} excluded")
    for a, n, pops, name in preserve:
        print(f"  preserve 0x{a:06X} {name} (args {n}, {'callee' if pops else 'caller'} pops)")
    for a, why in exclude:
        print(f"  EXCLUDE  0x{a:06X} {names.get(a, ('', '?'))[1]}: {why}")


if __name__ == "__main__":
    main()
